package service;

import model.Mission;

/**
 * Паттерн: Strategy.
 *
 * Определяет единый интерфейс для всех алгоритмов формирования отчёта.
 * Клиент (MainFrame) работает только с этим интерфейсом — конкретный алгоритм
 * (полный отчёт, сводка, анализ рисков, плагин-отчёт) подставляется в рантайме.
 *
 * Добавление нового типа отчёта = реализация этого интерфейса.
 * Существующий код не меняется (принцип OCP).
 */
public interface ReportFormatter {
    /** Формирует текст отчёта для переданной миссии */
    String format(Mission mission);

    /** Название, отображаемое в выпадающем списке «Тип отчёта» */
    String getDisplayName();
}