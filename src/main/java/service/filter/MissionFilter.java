package service.filter;

import model.Mission;

/**
 * Паттерн: Chain of Responsibility — интерфейс обработчика.
 *
 * Каждый фильтр инкапсулирует один критерий отбора миссий.
 * FilterChain собирает цепочку из произвольного числа фильтров и прогоняет
 * каждую миссию через все звенья — миссия проходит только если все фильтры
 * вернули true (логическое AND).
 *
 * Добавление нового критерия = новый класс, реализующий этот интерфейс.
 * Существующие фильтры и FilterChain не меняются (OCP).
 */
public interface MissionFilter {

    /** Возвращает true, если миссия соответствует критерию этого фильтра */
    boolean test(Mission mission);

    /** Человекочитаемое описание фильтра (для отображения в UI) */
    String getDisplayName();

    /** Идентификатор типа фильтра (для восстановления состояния UI без instanceof) */
    String getFilterId();

    /** Значение фильтра в текстовом виде (для восстановления состояния UI) */
    String getValue();
}
